    def unload(self):
        """プラグインのアンロード時の処理"""
        # HTTPサーバーを停止
        self.server_manager.stop_http_server()

        # パネルを削除
        if self.panel is not None:
            self.iface.removeDockWidget(self.panel)
            self.panel = None

        # シグナルを切断
        if hasattr(self, 'navigation_signals'):
            self.navigation_signals.navigate_requested.disconnect()

        # メニュー/ツールバー項目の除去はイベント完了後へ遅延する
        # (QMenu イベント処理中の除去は access violation の実績)
        _defer_remove_actions(
            self.iface, self.tr(u'&geo_webview'), list(self.actions),
            self._geo_toolbar(ensure_visible=False))

        # 自動再エクスポートのシグナル接続を解除
        if getattr(self, '_auto_export_connected', False):
            try:
                from qgis.core import QgsProject
                QgsProject.instance().projectSaved.disconnect(
                    self._on_project_saved)
            except Exception:  # nosec B110  # 設計上の許容
                pass
            self._auto_export_connected = False

        # ライブ連携の監視を停止
        try:
            if getattr(self, '_live_sync', None) is not None:
                self._live_sync.detach()
        except Exception:  # nosec B110  # 設計上の許容
            pass
        self._live_sync = None

        # AI/外部制御用ブリッジを解除
        self.bridge = None

