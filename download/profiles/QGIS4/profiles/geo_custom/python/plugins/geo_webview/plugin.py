        tb = self.iface.mainWindow().findChild(QToolBar, "GeoSuite")
        if tb is None:
            tb = self.iface.addToolBar("GeoSuite")
            tb.setObjectName("GeoSuite")
        if ensure_visible:
            tb.setVisible(True)
        return tb

