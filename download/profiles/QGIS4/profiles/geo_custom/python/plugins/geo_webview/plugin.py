        """パネルの表示/非表示を切り替え"""
        if not PANEL_AVAILABLE:
            QMessageBox.warning(
                self.iface.mainWindow(),
                self.tr("geo_webview"),
                self.tr("Panel functionality is not available.")
            )
            return

